"""Generate the keyboard dictionary from rime-ice -> keyboard/dict.js

Source: third_party/rime-ice (GPL-3.0, https://github.com/iDvel/rime-ice)
  8105.dict.yaml  common characters (8105, with readings and weights)
  base.dict.yaml  base words (~550k entries)
Each line: word \t space-separated pinyin \t weight

Output: window.PINYIN_DICT = {syllables:[...], words:{"nihao":"你好:2bx 拟好:k", ...}}   (same format as before; weight in base36)
Usage: python -I tools/gen_dict.py [max base words, default 200000]
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "rime-ice")
OUT = os.path.join(ROOT, "keyboard", "dict.js")
MAX_WORDS = int(sys.argv[1]) if len(sys.argv) > 1 else 200000
LINE = re.compile(r"^([^\t#]+)\t([a-zü ]+)\t(\d+)$")


def b36(n):
    s = ""
    while True:
        n, r = divmod(n, 36)
        s = "0123456789abcdefghijklmnopqrstuvwxyz"[r] + s
        if n == 0:
            return s


def read(name):
    body = False
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line == "...":
                body = True
                continue
            m = LINE.match(line) if body else None
            if m:
                yield m.group(1), m.group(2).replace("ü", "v").split(), int(m.group(3))


table, syllables = {}, set()


def add(word, syls, w):
    key = "".join(syls)
    cur = table.setdefault(key, {})
    cur[word] = max(cur.get(word, 0), w)


for c, syls, w in read("8105.dict.yaml"):
    if len(syls) == 1:
        syllables.add(syls[0])
        add(c, syls, w)

words = [x for x in read("base.dict.yaml") if 2 <= len(x[0]) <= 8 and len(x[0]) == len(x[1])]
words.sort(key=lambda x: -x[2])
for word, syls, w in words[:MAX_WORDS]:
    if all(s in syllables for s in syls):
        add(word, syls, w)

out = {k: " ".join(f"{w}:{b36(fr)}" for w, fr in sorted(v.items(), key=lambda x: -x[1])) for k, v in table.items()}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_dict.py from rime-ice (GPL-3.0). Do not edit.\n")
    f.write("window.PINYIN_DICT = " + json.dumps({"syllables": sorted(syllables), "words": out}, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"syllables={len(syllables)} keys={len(out)} words={min(MAX_WORDS, len(words))} size={os.path.getsize(OUT) // 1024}KB")
